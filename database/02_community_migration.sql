-- 기존 JWT 테이블까지 만든 MOVIEMATE 접속에서 F5로 최초 1회 실행.
-- 기존 리뷰도 승인 대기로 전환합니다. 삭제하지 않습니다.
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
ALTER TABLE MM_MEMBER_MOVIE ADD (
 review_status VARCHAR2(10 CHAR) DEFAULT 'PENDING' NOT NULL,
 review_revision NUMBER DEFAULT 0 NOT NULL,
 rejection_note VARCHAR2(300 CHAR),
 moderated_at TIMESTAMP,
 CONSTRAINT CK_MM_REVIEW_STATUS CHECK(review_status IN ('PENDING','APPROVED','REJECTED'))
);
CREATE TABLE MM_REVIEW_COMMENT (
 comment_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 review_member_id NUMBER NOT NULL,
 movie_id NUMBER NOT NULL,
 author_id NUMBER NOT NULL,
 content VARCHAR2(500 CHAR) NOT NULL,
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT FK_MM_COMMENT_REVIEW FOREIGN KEY(review_member_id,movie_id)
 REFERENCES MM_MEMBER_MOVIE(member_id,movie_id) ON DELETE CASCADE,
 CONSTRAINT FK_MM_COMMENT_AUTHOR FOREIGN KEY(author_id)
 REFERENCES MM_MEMBER(member_id) ON DELETE CASCADE
);
CREATE INDEX IX_MM_COMMENT_REVIEW ON MM_REVIEW_COMMENT(review_member_id,movie_id,comment_id);
CREATE INDEX IX_MM_COMMENT_AUTHOR ON MM_REVIEW_COMMENT(author_id);
CREATE INDEX IX_MM_REVIEW_STATUS ON MM_MEMBER_MOVIE(review_status,reviewed_at);
COMMIT;
