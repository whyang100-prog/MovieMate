-- MOVIEMATE / XEPDB1 접속에서 F5로 최초 1회 실행.
-- 기존 MM_MOVIE, MM_GENRE, MM_MOVIE_GENRE와 100편은 유지합니다.
-- 이미 같은 테이블이 있으면 재실행하지 말고 먼저 구조를 확인하세요.
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CREATE TABLE MM_MEMBER (
 member_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 username VARCHAR2(30 CHAR) NOT NULL UNIQUE,
 password_hash VARCHAR2(100 CHAR) NOT NULL,
 nickname VARCHAR2(30 CHAR) NOT NULL,
 role VARCHAR2(10 CHAR) DEFAULT 'USER' NOT NULL,
 enabled NUMBER(1) DEFAULT 1 NOT NULL,
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT CK_MM_MEMBER_ROLE CHECK (role IN ('USER','ADMIN')),
 CONSTRAINT CK_MM_MEMBER_ENABLED CHECK (enabled IN (0,1))
);
CREATE TABLE MM_MEMBER_MOVIE (
 member_id NUMBER NOT NULL,
 movie_id NUMBER NOT NULL,
 rating NUMBER(1) DEFAULT 0 NOT NULL,
 review VARCHAR2(500 CHAR),
 favorite NUMBER(1) DEFAULT 0 NOT NULL,
 reviewed_at TIMESTAMP,
 CONSTRAINT PK_MM_MEMBER_MOVIE PRIMARY KEY(member_id,movie_id),
 CONSTRAINT FK_MM_MM_MEMBER FOREIGN KEY(member_id) REFERENCES MM_MEMBER(member_id) ON DELETE CASCADE,
 CONSTRAINT FK_MM_MM_MOVIE FOREIGN KEY(movie_id) REFERENCES MM_MOVIE(movie_id) ON DELETE CASCADE,
 CONSTRAINT CK_MM_MM_RATING CHECK(rating BETWEEN 0 AND 5),
 CONSTRAINT CK_MM_MM_FAVORITE CHECK(favorite IN (0,1))
);
CREATE INDEX IX_MM_MM_MOVIE ON MM_MEMBER_MOVIE(movie_id);
-- 기존 poster_url(1000자)에 업로드 이미지 문자열을 넣지 않도록 분리
CREATE TABLE MM_MOVIE_MEDIA (
 movie_id NUMBER PRIMARY KEY,
 image_data CLOB,
 CONSTRAINT FK_MM_MEDIA_MOVIE FOREIGN KEY(movie_id) REFERENCES MM_MOVIE(movie_id) ON DELETE CASCADE
);
COMMIT;

-- JWT 로그인 장치별 Refresh Token 해시와 만료 정보
CREATE TABLE MM_AUTH_SESSION (
 session_id VARCHAR2(36 CHAR) PRIMARY KEY,
 member_id NUMBER NOT NULL,
 refresh_hash VARCHAR2(64 CHAR) NOT NULL,
 expires_at TIMESTAMP NOT NULL,
 CONSTRAINT FK_MM_AUTH_MEMBER FOREIGN KEY(member_id) REFERENCES MM_MEMBER(member_id) ON DELETE CASCADE
);
CREATE INDEX IX_MM_AUTH_MEMBER ON MM_AUTH_SESSION(member_id);
COMMIT;
